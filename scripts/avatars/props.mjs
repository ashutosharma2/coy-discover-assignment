export function glasses(kind, { lx, rx, y, ls, rs }) {
  const styles = {
    wire: { r: 50, color: "#c9a44a", w: 6 },
    square: { r: 50, color: INK, w: 13, square: true },
    round: { r: 48, color: "#2a2a2e", w: 7 },
    cat: { r: 50, color: "#16131a", w: 10, cat: true },
    tortoise: { r: 50, color: "#7b4a22", w: 11, square: true },
  };
  const s = styles[kind];
  const lens = (x, k, out) => {
    const r = s.r * k;
    const pts = s.cat
      ? [[x - out * r * 0.95, y - 26], [x, y - 30], [x + out * r * 0.7, y - 34], [x + out * r * 1.14, y - 48], [x + out * r * 0.92, y + 16], [x, y + 36], [x - out * r * 0.88, y + 16]]
      : s.square
        ? [[x - r, y - 36], [x + r, y - 36], [x + r, y + 34], [x - r, y + 34]]
        : null;
    if (!pts) return `<circle cx="${x}" cy="${y}" r="${r}" fill="#dbe9f0" fill-opacity="0.18" stroke="${s.color}" stroke-width="${s.w}"/>`;
    if (s.square) return box(pts, "#dbe9f000", { w: s.w, ink: s.color });
    return fill(pts, "#dbe9f0", 0.18) + outline(pts, { w: s.w, color: s.color });
  };
  const bridge = line([[lx + s.r * ls - 6, y - 8], [(lx + rx) / 2, y - 16], [rx - s.r * rs + 6, y - 8]], s.color, s.w * 0.75);
  const armL = line([[lx - s.r * ls, y - 12], [lx - s.r * ls - 44, y - 18]], s.color, s.w * 0.75);
  const armR = line([[rx + s.r * rs, y - 12], [rx + s.r * rs + 44, y - 18]], s.color, s.w * 0.75);
  return armL + armR + lens(lx, ls, -1) + lens(rx, rs, 1) + bridge;
}

